-- Re-run of setup v2 with an explicit key reset and a fingerprint check (31 October 2026).
-- Written after the first connection attempt failed with "JWT token is invalid" for both
-- users. Every statement is idempotent. Run with "Run All" (Ctrl/Cmd+Shift+Enter), not "Run".
-- Placeholders as in snowflake-setup-v2.sql, plus <RO_KEY_FP> and <LOADER_KEY_FP>, the
-- SHA256 fingerprints of the two public keys. The final result has two rows; both
-- KEY_MATCHES values must be TRUE.


USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS SLSTUDY_RO;
CREATE ROLE IF NOT EXISTS SLSTUDY_LOADER;
GRANT ROLE SLSTUDY_RO TO ROLE SLSTUDY_LOADER;
GRANT ROLE SLSTUDY_LOADER TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS SLSTUDY_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS SLSTUDY_RM
  WITH CREDIT_QUOTA = 5
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

-- Warehouse ceiling 600 s for loading; the executor user is capped at 120 s below.
ALTER WAREHOUSE SLSTUDY_WH SET
  RESOURCE_MONITOR = SLSTUDY_RM
  STATEMENT_TIMEOUT_IN_SECONDS = 600;

GRANT USAGE ON WAREHOUSE SLSTUDY_WH TO ROLE SLSTUDY_RO;

CREATE DATABASE IF NOT EXISTS SLSTUDY;
GRANT USAGE ON DATABASE SLSTUDY TO ROLE SLSTUDY_RO;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE SLSTUDY TO ROLE SLSTUDY_RO;
GRANT SELECT ON FUTURE TABLES IN DATABASE SLSTUDY TO ROLE SLSTUDY_RO;
GRANT SELECT ON FUTURE VIEWS IN DATABASE SLSTUDY TO ROLE SLSTUDY_RO;
GRANT OWNERSHIP ON DATABASE SLSTUDY TO ROLE SLSTUDY_LOADER COPY CURRENT GRANTS;

CREATE NETWORK POLICY IF NOT EXISTS SLSTUDY_NP ALLOWED_IP_LIST = ('<HOST_IP>');

CREATE USER IF NOT EXISTS SLSTUDY_USER
  TYPE = SERVICE
  DEFAULT_ROLE = SLSTUDY_RO
  DEFAULT_WAREHOUSE = SLSTUDY_WH
  RSA_PUBLIC_KEY = '<RO_PUBLIC_KEY>';
GRANT ROLE SLSTUDY_RO TO USER SLSTUDY_USER;
ALTER USER SLSTUDY_USER SET
  STATEMENT_TIMEOUT_IN_SECONDS = 120
  NETWORK_POLICY = SLSTUDY_NP;

CREATE USER IF NOT EXISTS SLSTUDY_LOADER_USER
  TYPE = SERVICE
  DEFAULT_ROLE = SLSTUDY_LOADER
  DEFAULT_WAREHOUSE = SLSTUDY_WH
  RSA_PUBLIC_KEY = '<LOADER_PUBLIC_KEY>';
GRANT ROLE SLSTUDY_LOADER TO USER SLSTUDY_LOADER_USER;
ALTER USER SLSTUDY_LOADER_USER SET NETWORK_POLICY = SLSTUDY_NP;

-- Reset the keys in case the users already existed or the key text was altered.
ALTER USER SLSTUDY_USER SET RSA_PUBLIC_KEY = '<RO_PUBLIC_KEY>';
ALTER USER SLSTUDY_LOADER_USER SET RSA_PUBLIC_KEY = '<LOADER_PUBLIC_KEY>';

DESC USER SLSTUDY_USER;
SET q1 = LAST_QUERY_ID();
DESC USER SLSTUDY_LOADER_USER;
SET q2 = LAST_QUERY_ID();
SELECT 'SLSTUDY_USER' AS user_name,
       MAX(IFF("property" = 'RSA_PUBLIC_KEY_FP', "value", NULL)) = '<RO_KEY_FP>' AS key_matches,
       MAX(IFF("property" = 'TYPE', "value", NULL)) AS user_type,
       MAX(IFF("property" = 'DISABLED', "value", NULL)) AS disabled,
       MAX(IFF("property" = 'NETWORK_POLICY', "value", NULL)) AS network_policy
FROM TABLE(RESULT_SCAN($q1))
UNION ALL
SELECT 'SLSTUDY_LOADER_USER',
       MAX(IFF("property" = 'RSA_PUBLIC_KEY_FP', "value", NULL)) = '<LOADER_KEY_FP>',
       MAX(IFF("property" = 'TYPE', "value", NULL)),
       MAX(IFF("property" = 'DISABLED', "value", NULL)),
       MAX(IFF("property" = 'NETWORK_POLICY', "value", NULL))
FROM TABLE(RESULT_SCAN($q2));
