"""Generate the paper's results section from results/<stage>-ANALYSIS.json (no hand-typed numbers).

  build_results.py <stage>  ->  paper/RESULTS-<stage>.md
"""
import json
import pathlib
import sys

PAPER = pathlib.Path(__file__).resolve().parent
RES = PAPER.parent / "results"
NAMES = {"opus": "Claude Opus 5.5", "sol": "GPT-6.1 Sol", "haiku": "Claude Haiku 5.5"}
OPS = ["formula_drift", "hidden_filter", "synonym", "fiscal_definition", "relationship_key", "value_mapping"]


def pct(x):
    return "–" if x is None else f"{100 * x:.0f}%"


def ci(h):
    p = h and h.get("pooled")
    if not p:
        return "not estimable"
    return f"{100 * p['estimate']:+.0f} points [95% CI {100 * p['ci95'][0]:+.0f}, {100 * p['ci95'][1]:+.0f}]"


def main():
    stage = sys.argv[1]
    a = json.loads((RES / f"{stage}-ANALYSIS.json").read_text())
    rows = {(r["model"], r["arm"]): r for r in a["by_model_arm"]}
    arms_all = {(r["arm"]): r for r in a["by_arm"]}
    ops = {(r["operator"], r["arm"]): r for r in a["by_operator_arm"]}
    H = a["hypotheses"]
    out = [f"# Results ({stage}; generated by paper/build_results.py from results/{stage}-ANALYSIS.json)\n",
           f"{a['trials']} trials; total model cost ${sum(a['cost_usd'].values()):.2f} "
           + "(" + ", ".join(f"{NAMES[m]} ${c:.2f}" for m, c in a["cost_usd"].items()) + ").\n"]

    out.append("## A correct layer helps; a wrong one is followed\n")
    out.append("| Model | C0 correct | C1 correct | E correct | F1 correct | F1 followed | F2 correct | F2 followed |")
    out.append("|---|---|---|---|---|---|---|---|")
    for m in NAMES:
        g = lambda arm, k: rows.get((m, arm), {}).get(k)  # noqa: E731
        out.append(f"| {NAMES[m]} | {pct(g('C0', 'correct'))} | {pct(g('C1', 'correct'))} | {pct(g('E', 'correct'))} | "
                   f"{pct(g('F1', 'correct'))} | {pct(g('F1', 'fault_match'))} | {pct(g('F2', 'correct'))} | {pct(g('F2', 'fault_match'))} |")
    out.append("")
    out.append(f"- **H1 (coherent faults are followed more than contradictory ones):** fault-following F1 − F2 = {ci(H.get('H1'))}.")
    out.append(f"- **H2 (a missing element beats a wrong one):** correct E − F1 = {ci(H.get('H2'))}.")
    out.append(f"- Value of the correct layer (exploratory X4): correct C1 − C0 = {ci(H.get('X4'))}; "
               f"layer minus the anchored element (X5): correct E − C0 = {ci(H.get('X5'))}.\n")

    out.append("## Silent failure\n")
    out.append("| Model | Arm | Trials | Followed the fault | Of those, silent | Silent / trials |")
    out.append("|---|---|---|---|---|---|")
    for key, s in a["silent_failure"].items():
        m, arm = key.split("/")
        out.append(f"| {NAMES[m]} | {arm} | {s['trials']} | {s['fault_match']} | {s['silent']} | {pct(s['silent_over_trials'])} |")
    out.append("")

    out.append("## Detection and the cost of skepticism\n")
    out.append("| Model | D1 on F1 | D2 on F1 | D1 on F2 | D2 on F2 | Layer concerns C1 | C1+A | C1+N |")
    out.append("|---|---|---|---|---|---|---|---|")
    for m in NAMES:
        g = lambda arm, k: rows.get((m, arm), {}).get(k)  # noqa: E731
        out.append(f"| {NAMES[m]} | {pct(g('F1', 'd1'))} | {pct(g('F1', 'd2'))} | {pct(g('F2', 'd1'))} | {pct(g('F2', 'd2'))} | "
                   f"{pct(g('C1', 'd1'))} | {pct(g('C1A', 'd1'))} | {pct(g('C1N', 'd1'))} |")
    out.append("")
    out.append(f"- **H3a (audit raises located detection on F2):** {ci(H.get('H3a'))}.")
    out.append(f"- **H3b (audit raises layer concerns on the correct layer):** {ci(H.get('H3b'))}.")
    out.append(f"- Exploratory: audit reduces *following* of contradictory faults (X1, F2 − F2+A) {ci(H.get('X1'))}; "
               f"of coherent faults (X2, F1 − F1+A) {ci(H.get('X2'))}; silent failure on coherent faults (X3, F1 − F1+A) {ci(H.get('X3'))}.\n")

    out.append("## By fault operator (all models pooled)\n")
    out.append("| Operator | F1 followed | F1 silent | F2 followed | F2 D2 | F1+A followed |")
    out.append("|---|---|---|---|---|---|")
    for op in OPS:
        g = lambda arm, k: ops.get((op, arm), {}).get(k)  # noqa: E731
        out.append(f"| {op} | {pct(g('F1', 'fault_match'))} | {pct(g('F1', 'silent'))} | {pct(g('F2', 'fault_match'))} | "
                   f"{pct(g('F2', 'd2'))} | {pct(g('F1A', 'fault_match'))} |")
    out.append("")
    out.append("Per-model per-hypothesis estimates, operator-cluster sensitivity intervals and GEE checks are in the "
               f"analysis JSON; the full rate table is `results/{stage}-TABLES.md`.")
    (PAPER / f"RESULTS-{stage}.md").write_text("\n".join(out) + "\n")
    print(PAPER / f"RESULTS-{stage}.md")


if __name__ == "__main__":
    main()
